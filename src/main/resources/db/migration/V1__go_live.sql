-- Go live.
--
-- Every table the desk starts with: airports, carriers, rates and mileages, the tariff and its
-- loads, what the collectors saw, and the desk's own tickets, watches, recommendations and runs.
--
-- Written by hand and read line by line against the mapping, which a test compares it with.
-- Every constraint and index is named as a function of its table and columns, so a later
-- migration that drops one can name it. Each table's foreign keys are added after its indexes,
-- so the database backs each key with the index already declared for it rather than a second
-- one of its own. Tables come in the one order the foreign keys allow.

CREATE TABLE airports (
    code               VARCHAR(3)       NOT NULL,
    name               VARCHAR(64)      NOT NULL,
    city               VARCHAR(3)       NOT NULL,
    country            VARCHAR(2)       NOT NULL,
    latitude           DOUBLE PRECISION NOT NULL,
    longitude          DOUBLE PRECISION NOT NULL,
    utc_offset_minutes INTEGER          NOT NULL,
    source             VARCHAR(16)      NOT NULL,
    created_at         TIMESTAMP(6)     NOT NULL,
    updated_at         TIMESTAMP(6)     NOT NULL,
    CONSTRAINT pk_airports PRIMARY KEY (code)
);
CREATE INDEX ix_airports_city ON airports (city);
CREATE INDEX ix_airports_country ON airports (country);

CREATE TABLE carriers (
    code       VARCHAR(2)   NOT NULL,
